const LEGACY_THEME_ALIAS: Record<string, string> = {
  theme_twilight: 'theme_twilightSpace',
  theme_midnight: 'theme_darkest',
  theme_crimson: 'theme_cherryDark',
  theme_emerald: 'theme_limeDark',
  theme_amber: 'theme_duskHorizon',
  theme_dusk: 'theme_duskHorizon',
};

export function getThemeById(id?: string | null): AppTheme {
  const resolved = (id && LEGACY_THEME_ALIAS[id]) || id;
  return APP_THEMES.find((t) => t.id === resolved) ?? APP_THEMES[0];
}
